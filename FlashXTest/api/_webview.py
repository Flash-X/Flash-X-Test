"""Python API for FlashXTest"""

import os
from pathlib import Path

from .. import lib
from .. import backend


def webview(outdir=None, force_rewrite=False, results=None):
    """
    Generate a static, read-only, self-contained webview.

    Arguments
    ---------
    outdir        : Output directory. Defaults to "pathToWebview" from
                    "config", then "./html".
    force_rewrite : Replace outdir even if it was not generated by webview
    results       : Results directory. Defaults to "pathToOutdir" from
                    "config", then "pathToViewArchive".
    """
    config = {}
    pathToConfig = os.path.join(os.getcwd(), "config")
    if (not outdir or not results) and os.path.exists(pathToConfig):
        config = lib.config.getMainDict({"pathToConfig": pathToConfig})

    outdir = outdir or config.get("pathToWebview") or "./html"
    results = (
        results or config.get("pathToOutdir") or config.get("pathToViewArchive")
    )

    if not results:
        raise ValueError(
            "No results directory found. Pass --results, or run from a directory "
            'with a "config" (flashxtest init).'
        )

    backend.Webview.generate_flashx_testview(
        target_dir=Path(results),
        output_dir=Path(outdir),
        force_rewrite=force_rewrite,
    )
